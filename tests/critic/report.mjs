// Regenerates docs/critic/SCOREBOARD.md from every round's critic replies.
//
//   node tests/critic/report.mjs
//
// A round is a folder docs/critic/r*/ (sorted by name). Every *.json in it that has a "scores"
// object is one critic's reply (video-critic.json, stills-critic.json, gemini.json, ...): the critic
// is named by its "critic" field, else by the file name. One table row per round and critic with the
// eight scores and their mean, then each round's one-line reviews.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const docs = path.join(root, 'docs', 'critic');

const KEYS = [
  ['visual_appeal', 'Look'],
  ['readability', 'Read'],
  ['game_feel', 'Feel'],
  ['fun_factor', 'Fun'],
  ['variety', 'Variety'],
  ['sense_of_progression', 'Progress'],
  ['want_to_keep_playing', 'Keep playing'],
  ['would_wishlist', 'Wishlist'],
];
// Table-safe text; the project never uses em dashes, so a critic's become spaced hyphens.
const cell = (s) =>
  String(s ?? '')
    .replace(/\s*\u2014\s*/g, ' - ')
    .replace(/\|/g, '\\|')
    .replace(/\r?\n/g, ' ');

const rounds = fs.existsSync(docs)
  ? fs
      .readdirSync(docs, { withFileTypes: true })
      .filter((d) => d.isDirectory() && /^r/i.test(d.name))
      .map((d) => d.name)
      .sort()
  : [];

const rows = [];
const reviews = [];
for (const round of rounds) {
  const dir = path.join(docs, round);
  const found = [];
  for (const f of fs.readdirSync(dir).filter((f) => f.endsWith('.json')).sort()) {
    let j;
    try {
      j = JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'));
    } catch {
      console.warn(`skipped ${round}/${f}: not valid JSON`);
      continue;
    }
    if (!j || typeof j.scores !== 'object' || j.scores === null) continue;
    const critic = j.critic || f.replace(/\.json$/, '');
    const vals = KEYS.map(([k]) => (typeof j.scores[k] === 'number' ? j.scores[k] : null));
    const nums = vals.filter((v) => v !== null);
    const mean = nums.length ? nums.reduce((a, b) => a + b, 0) / nums.length : null;
    found.push({ critic, file: f, vals, mean, line: j.one_line_review, worst: j.worst_problems?.[0] });
  }
  for (const c of found) rows.push({ round, ...c });
  reviews.push({ round, critics: found });
}

const out = [
  '# Critic scoreboard',
  '',
  'Generated by `node tests/critic/report.mjs` from `docs/critic/r*/*.json`. Do not edit by hand.',
  'Scores are 1 to 10 from a "random gamer" critic who sees only footage and the store blurb (see `docs/critic/README.md`).',
  '',
];
if (!rows.length) {
  out.push('No critic scores yet.', '');
} else {
  out.push(
    `| Round | Critic | ${KEYS.map(([, h]) => h).join(' | ')} | Mean |`,
    `| --- | --- | ${KEYS.map(() => '---:').join(' | ')} | ---: |`,
    ...rows.map((r) => `| ${cell(r.round)} | ${cell(r.critic)} | ${r.vals.map((v) => (v === null ? '-' : v)).join(' | ')} | ${r.mean === null ? '-' : r.mean.toFixed(2)} |`),
    '',
    '## One-line reviews',
    '',
  );
  for (const r of reviews) {
    if (!r.critics.length) continue;
    out.push(`### ${r.round}`, '');
    for (const c of r.critics) {
      out.push(`- **${cell(c.critic)}**: ${cell(c.line || '(no one-line review)')}`);
      if (c.worst?.problem) out.push(`  - worst problem (${cell(c.worst.severity || '?')}): ${cell(c.worst.problem)}`);
    }
    out.push('');
  }
}
fs.mkdirSync(docs, { recursive: true });
fs.writeFileSync(path.join(docs, 'SCOREBOARD.md'), out.join('\n'));
console.log(`SCOREBOARD.md: ${rows.length} critic replies across ${reviews.filter((r) => r.critics.length).length} rounds`);
